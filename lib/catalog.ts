export function getCategory(slug: Slug): Category {
  const c = CATEGORIES.find((x) => x.slug === slug);
  if (!c) throw new Error(`Нет направления ${slug}`);
  return c;
}

export function categoriesByGroup(group: GroupName) {
  return CATEGORIES.filter((c) => c.group === group);
}

export function categoriesByHub(hub: HubKey) {
  return CATEGORIES.filter((c) => c.hub === hub);
}
